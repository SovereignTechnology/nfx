/** Normalised probe result; both `ffprobe -print_format json` and bare-media map to this. */
export interface MediaProbe {
  readonly container: string; // e.g. "mov,mp4,m4a,3gp,3g2,mj2", "matroska,webm"
  readonly durationSec: number;
  readonly bitrateKbps?: number;
  readonly video?: {
    readonly codec: string; // "h264", "hevc", "vp9", "av1"
    readonly width: number;
    readonly height: number;
    readonly fps: number;
    readonly rotation?: number;
    readonly pixelFormat?: string;
  };
  readonly audio?: {
    readonly codec: string;
    readonly channels: number;
    readonly sampleRate: number;
  };
  /** True when `moov` precedes `mdat` (range playback starts immediately). */
  readonly faststart?: boolean;
}

export interface RenditionSpec {
  readonly label: string; // "1080p" | "720p" | "360p" — never taller than the source
  readonly height: number;
  readonly videoBitrateKbps: number;
  readonly audioBitrateKbps: number;
  readonly codec: 'h264' | 'vp9' | 'av1';
  readonly container: 'mp4' | 'webm';
}

export interface LadderPlan {
  readonly source: MediaProbe;
  readonly renditions: readonly RenditionSpec[];
  /** Seconds at which to grab thumbnail candidates. */
  readonly thumbnailTimes: readonly number[];
  readonly storyboard?: {
    readonly intervalSec: number;
    readonly cols: number;
    readonly rows: number;
    readonly tileWidth: number;
  };
}

// ---- demo-base:packages/core/src/media/errors.ts ----

export type MediaErrorCode =
  | 'ffmpeg-not-found'
  | 'process-failed'
  | 'probe-parse'
  | 'no-video-stream'
  | 'not-faststart'
  | 'hash-mismatch'
  | 'unsupported-input'
  | 'aborted';

export class MediaError extends Error {
  override readonly name = 'MediaError' as const;
  readonly code: MediaErrorCode;
  /** Captured stderr of the failing process, when there is one. Never logged by us. */
  readonly stderr?: string;

  constructor(
    code: MediaErrorCode,
    message: string,
    opts: { readonly cause?: unknown; readonly stderr?: string } = {},
  ) {
    super(message, { cause: opts.cause });
    this.code = code;
    if (opts.stderr !== undefined) this.stderr = opts.stderr;
  }
}

// ---- demo-base:packages/core/src/media/ffprobe.ts ----

/** Argv for probing `path`. `path` is a single argv element — never shell-interpolated. */
export function ffprobeArgv(path: string): readonly string[] {
  return [
    '-hide_banner',
    '-v',
    'error',
    '-print_format',
    'json',
    '-show_format',
    '-show_streams',
    // `--` is not understood by ffprobe; a leading `-` in a filename is disambiguated by
    // the caller passing an absolute path, which the pipeline always does.
    path,
  ];
}

interface RawStream {
  readonly codec_type?: unknown;
  readonly codec_name?: unknown;
  readonly width?: unknown;
  readonly height?: unknown;
  readonly r_frame_rate?: unknown;
  readonly avg_frame_rate?: unknown;
  readonly pix_fmt?: unknown;
  readonly channels?: unknown;
  readonly sample_rate?: unknown;
  readonly bit_rate?: unknown;
  readonly disposition?: { readonly attached_pic?: unknown };
  readonly side_data_list?: readonly { readonly rotation?: unknown }[];
  readonly tags?: { readonly rotate?: unknown };
}

interface RawProbe {
  readonly streams?: readonly RawStream[];
  readonly format?: {
    readonly format_name?: unknown;
    readonly duration?: unknown;
    readonly bit_rate?: unknown;
  };
}

function num(v: unknown): number | undefined {
  if (typeof v === 'number') return Number.isFinite(v) ? v : undefined;
  if (typeof v === 'string' && v.trim() !== '') {
    const n = Number(v);
    return Number.isFinite(n) ? n : undefined;
  }
  return undefined;
}

function str(v: unknown): string | undefined {
  return typeof v === 'string' ? v : undefined;
}

function isObjectArray<T extends object>(v: readonly T[] | undefined): v is readonly T[] {
  return Array.isArray(v) && v.every((s: unknown) => typeof s === 'object' && s !== null);
}

/** "30000/1001" → 29.97; "0/0" → undefined. */
export function parseRational(v: unknown): number | undefined {
  const s = str(v);
  if (!s) return num(v);
  const m = /^(\d+)\s*\/\s*(\d+)$/.exec(s.trim());
  if (!m) return num(s);
  const a = Number(m[1]);
  const b = Number(m[2]);
  if (b === 0 || !Number.isFinite(a) || !Number.isFinite(b)) return undefined;
  return a / b;
}

/** Normalises any rotation value to one of 0/90/180/270. */
export function normaliseRotation(v: unknown): number | undefined {
  const n = num(v);
  if (n === undefined) return undefined;
  const r = ((Math.round(n) % 360) + 360) % 360;
  return r;
}

export function parseFfprobeJson(text: string): MediaProbe {
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch (e) {
    throw new MediaError('probe-parse', 'ffprobe output is not JSON', { cause: e });
  }
  if (typeof raw !== 'object' || raw === null) {
    throw new MediaError('probe-parse', 'ffprobe output is not an object');
  }
  const p = raw as RawProbe;
  const streams: readonly RawStream[] = isObjectArray(p.streams) ? p.streams : [];
  const format: NonNullable<RawProbe['format']> = typeof p.format === 'object' ? p.format : {};

  const container = str(format.format_name);
  if (!container) throw new MediaError('probe-parse', 'ffprobe: missing format.format_name');

  const video = streams.find(
    (s) => s.codec_type === 'video' && num(s.disposition?.attached_pic) !== 1,
  );
  const audio = streams.find((s) => s.codec_type === 'audio');

  let durationSec = num(format.duration);
  if (durationSec === undefined) {
    // Some containers (raw streams) carry duration only on the stream.
    const sd = num((video as { duration?: unknown } | undefined)?.duration);
    durationSec = sd ?? 0;
  }

  const bitrate = num(format.bit_rate);

  let videoInfo: MediaProbe['video'];
  if (video) {
    const codec = str(video.codec_name);
    const width = num(video.width);
    const height = num(video.height);
    if (!codec || width === undefined || height === undefined) {
      throw new MediaError('probe-parse', 'ffprobe: video stream lacks codec/width/height');
    }
    const fps = parseRational(video.avg_frame_rate) ?? parseRational(video.r_frame_rate) ?? 0;
    const rotation =
      normaliseRotation(video.side_data_list?.find((d) => d.rotation !== undefined)?.rotation) ??
      normaliseRotation(video.tags?.rotate);
    const pixelFormat = str(video.pix_fmt);
    videoInfo = {
      codec,
      width,
      height,
      fps,
      ...(rotation !== undefined && rotation !== 0 ? { rotation } : {}),
      ...(pixelFormat !== undefined ? { pixelFormat } : {}),
    };
  }

  let audioInfo: MediaProbe['audio'];
  if (audio) {
    const codec = str(audio.codec_name) ?? 'unknown';
    audioInfo = {
      codec,
      channels: num(audio.channels) ?? 0,
      sampleRate: num(audio.sample_rate) ?? 0,
    };
  }

  return {
    container,
    durationSec,
    ...(bitrate !== undefined ? { bitrateKbps: Math.round(bitrate / 1000) } : {}),
    ...(videoInfo ? { video: videoInfo } : {}),
    ...(audioInfo ? { audio: audioInfo } : {}),
  };
}

/** Display dimensions after applying the container rotation (90/270 swap width/height). */
export function displayDimensions(video: NonNullable<MediaProbe['video']>): {
  readonly width: number;
  readonly height: number;
} {
  const rot = video.rotation ?? 0;
  return rot === 90 || rot === 270
    ? { width: video.height, height: video.width }
    : { width: video.width, height: video.height };
}

// ---- demo-base:packages/core/src/media/ladder.ts ----

interface Tier {
  readonly label: string;
  readonly height: number;
  readonly videoBitrateKbps: number;
  readonly audioBitrateKbps: number;
}

export const LADDER_TIERS: readonly Tier[] = [
  { label: '1080p', height: 1080, videoBitrateKbps: 5000, audioBitrateKbps: 128 },
  { label: '720p', height: 720, videoBitrateKbps: 2500, audioBitrateKbps: 128 },
  { label: '360p', height: 360, videoBitrateKbps: 800, audioBitrateKbps: 96 },
];

/** Keyframe interval in seconds — identical for every rendition so switches align. */
export const GOP_SECONDS = 2 as const;

/** Thumbnail candidate positions as fractions of the duration. */
export const THUMBNAIL_FRACTIONS: readonly number[] = [0.1, 0.3, 0.5, 0.7];

export const STORYBOARD_COLS = 10 as const;
export const STORYBOARD_TILE_WIDTH = 160 as const;
/** Storyboards aim for at most this many tiles; interval is picked from the list below. */
export const STORYBOARD_MAX_TILES = 100 as const;
const STORYBOARD_INTERVALS: readonly number[] = [1, 2, 5, 10, 20, 30, 60, 120, 300];

const codecContainer = (codec: RenditionSpec['codec']): RenditionSpec['container'] =>
  codec === 'vp9' ? 'webm' : 'mp4';

const bitrateScale = (codec: RenditionSpec['codec']): number =>
  codec === 'h264' ? 1 : codec === 'vp9' ? 0.7 : 0.55;

/** Even output size preserving aspect for a target height. */
export function fitToHeight(
  src: { readonly width: number; readonly height: number },
  height: number,
): { readonly width: number; readonly height: number } {
  const h = height - (height % 2);
  const w = Math.round((src.width * h) / src.height);
  return { width: w + (w % 2), height: h };
}

/** Thumbnail candidate timestamps for a duration, deduplicated and inside the clip. */
export function thumbnailTimes(durationSec: number): readonly number[] {
  if (!(durationSec > 0)) return [0];
  const times = THUMBNAIL_FRACTIONS.map((f) => Math.floor(durationSec * f * 1000) / 1000);
  const uniq = [...new Set(times)].filter((t) => t >= 0 && t < durationSec);
  return uniq.length > 0 ? uniq : [0];
}

export function storyboardGeometry(
  durationSec: number,
): NonNullable<LadderPlan['storyboard']> | undefined {
  if (!(durationSec > 0)) return undefined;
  const intervalSec =
    STORYBOARD_INTERVALS.find((i) => Math.ceil(durationSec / i) <= STORYBOARD_MAX_TILES) ??
    STORYBOARD_INTERVALS[STORYBOARD_INTERVALS.length - 1] ??
    300;
  const tiles = Math.max(1, Math.ceil(durationSec / intervalSec));
  const cols = Math.min(STORYBOARD_COLS, tiles);
  const rows = Math.ceil(tiles / cols);
  return { intervalSec, cols, rows, tileWidth: STORYBOARD_TILE_WIDTH };
}

export function planLadder(
  probe: MediaProbe,
  opts: { readonly maxHeight?: number; readonly codec?: RenditionSpec['codec'] } = {},
): LadderPlan {
  if (!probe.video) throw new MediaError('no-video-stream', 'input has no video stream');
  const codec = opts.codec ?? 'h264';
  const container = codecContainer(codec);
  const src = displayDimensions(probe.video);
  const cap = Math.min(src.height, opts.maxHeight ?? Infinity);
  const scale = bitrateScale(codec);

  let renditions: RenditionSpec[] = LADDER_TIERS.filter((t) => t.height <= cap).map((t) => ({
    label: t.label,
    height: t.height,
    videoBitrateKbps: Math.round(t.videoBitrateKbps * scale),
    audioBitrateKbps: t.audioBitrateKbps,
    codec,
    container,
  }));

  if (renditions.length === 0) {
    // Source is shorter than the lowest tier: one rendition at native (even) height.
    const h = Math.max(2, cap - (cap % 2));
    const lowest = LADDER_TIERS[LADDER_TIERS.length - 1];
    const vk = lowest ? Math.round((lowest.videoBitrateKbps * h) / lowest.height) : 400;
    renditions = [
      {
        label: `${h}p`,
        height: h,
        videoBitrateKbps: Math.max(200, Math.round(vk * scale)),
        audioBitrateKbps: lowest?.audioBitrateKbps ?? 96,
        codec,
        container,
      },
    ];
  }

  const storyboard = storyboardGeometry(probe.durationSec);
  return {
    source: probe,
    renditions,
    thumbnailTimes: thumbnailTimes(probe.durationSec),
    ...(storyboard ? { storyboard } : {}),
  };
}

// ---- demo-base:packages/core/src/media/argv.ts ----

const COMMON: readonly string[] = ['-hide_banner', '-nostdin', '-y', '-loglevel', 'error'];

export const THUMBNAIL_WIDTH = 640 as const;

export interface RenditionArgvOpts {
  readonly preset?: string;
  readonly fps: number;
}

/** GOP length in frames for keyframe-aligned switching: `fps × GOP_SECONDS`, min 1. */
export function gopFrames(fps: number): number {
  return Math.max(1, Math.round((fps > 0 ? fps : 30) * GOP_SECONDS));
}

/** The exact output dimensions a rendition will have (even, aspect-preserving). */
export function renditionDimensions(
  source: MediaProbe,
  spec: RenditionSpec,
): { readonly width: number; readonly height: number } {
  if (!source.video) throw new Error('renditionDimensions: source has no video');
  return fitToHeight(displayDimensions(source.video), spec.height);
}

function videoCodecArgs(spec: RenditionSpec, g: number, preset: string): readonly string[] {
  const vb = `${spec.videoBitrateKbps}k`;
  const maxrate = `${Math.round(spec.videoBitrateKbps * 1.5)}k`;
  const bufsize = `${spec.videoBitrateKbps * 2}k`;
  switch (spec.codec) {
    case 'h264':
      return [
        '-c:v',
        'libx264',
        '-preset',
        preset,
        '-profile:v',
        'high',
        '-pix_fmt',
        'yuv420p',
        '-b:v',
        vb,
        '-maxrate',
        maxrate,
        '-bufsize',
        bufsize,
        '-g',
        String(g),
        '-keyint_min',
        String(g),
        '-sc_threshold',
        '0',
      ];
    case 'vp9':
      return [
        '-c:v',
        'libvpx-vp9',
        '-pix_fmt',
        'yuv420p',
        '-b:v',
        vb,
        '-maxrate',
        maxrate,
        '-bufsize',
        bufsize,
        '-row-mt',
        '1',
        '-g',
        String(g),
        '-keyint_min',
        String(g),
      ];
    case 'av1':
      return [
        '-c:v',
        'libsvtav1',
        '-pix_fmt',
        'yuv420p',
        '-b:v',
        vb,
        '-maxrate',
        maxrate,
        '-bufsize',
        bufsize,
        '-g',
        String(g),
      ];
  }
}

function audioCodecArgs(spec: RenditionSpec): readonly string[] {
  const ab = `${spec.audioBitrateKbps}k`;
  return spec.container === 'webm'
    ? ['-c:a', 'libopus', '-b:a', ab, '-ac', '2', '-ar', '48000']
    : ['-c:a', 'aac', '-b:a', ab, '-ac', '2', '-ar', '48000'];
}

/**
 * One rendition. `-force_key_frames expr:gte(t,n_forced*2)` pins a keyframe every
 * GOP_SECONDS regardless of encoder heuristics, so every rendition's keyframes line up.
 */
export function renditionArgv(
  input: string,
  output: string,
  source: MediaProbe,
  spec: RenditionSpec,
  opts: RenditionArgvOpts,
): readonly string[] {
  const dims = renditionDimensions(source, spec);
  const g = gopFrames(opts.fps);
  const preset = opts.preset ?? 'medium';
  const container: readonly string[] =
    spec.container === 'mp4' ? ['-movflags', '+faststart', '-f', 'mp4'] : ['-f', 'webm'];
  return [
    ...COMMON,
    '-i',
    input,
    '-map',
    '0:v:0',
    '-map',
    '0:a:0?',
    '-vf',
    `scale=${dims.width}:${dims.height}`,
    ...videoCodecArgs(spec, g, preset),
    '-force_key_frames',
    `expr:gte(t,n_forced*${GOP_SECONDS})`,
    ...audioCodecArgs(spec),
    '-sn',
    '-dn',
    '-map_metadata',
    '-1',
    '-map_chapters',
    '-1',
    ...container,
    '-progress',
    'pipe:2',
    '-nostats',
    output,
  ];
}

/** Single JPEG frame at `timeSec`, input-side seek (fast), scaled to THUMBNAIL_WIDTH. */
export function thumbnailArgv(
  input: string,
  output: string,
  timeSec: number,
  width: number = THUMBNAIL_WIDTH,
): readonly string[] {
  return [
    ...COMMON,
    '-ss',
    formatSeconds(timeSec),
    '-i',
    input,
    '-frames:v',
    '1',
    '-vf',
    `scale='min(${width},iw)':-2`,
    '-q:v',
    '2',
    '-f',
    'image2',
    output,
  ];
}

/** Seconds as ffmpeg accepts them; fixed 3 decimals, never exponent notation. */
export function formatSeconds(t: number): string {
  return (Number.isFinite(t) && t > 0 ? t : 0).toFixed(3);
}
