//! The suite has teeth: each defect planted in the mock fails the scenario written for
//! it. The defects are every one the audits found in a plausible engine or viewer.
//! Against the honest mock every scenario passes (`adversary.rs`).

#![allow(clippy::unwrap_used, clippy::expect_used)]

use nfx_pay::adversary;
use nfx_pay::mock::{MockHarness, SeederFlaw as S, ViewerFlaw as V};

macro_rules! catches {
    ($($test:ident: $harness:expr => $scenario:ident),* $(,)?) => {
        $(
            #[test]
            fn $test() {
                // The defect must fail a check of the suite: a hang, a panic raised in the
                // engine, the harness or a runtime, or one at a line of the suite that makes
                // no check (a bare unwrap), names no behaviour, so none is a catch.
                let run = adversary::run_on_a_thread(10, || {
                    tokio::runtime::Builder::new_current_thread()
                        .enable_all()
                        .build()
                        .expect("a runtime")
                        .block_on(async { adversary::$scenario(&$harness).await })
                });
                match &run {
                    adversary::Ran::Finished => panic!(
                        "{} did not catch the planted defect",
                        stringify!($scenario)
                    ),
                    adversary::Ran::Hung => {
                        panic!("{} hung on the planted defect", stringify!($scenario))
                    }
                    adversary::Ran::Panicked { file, line, .. } => assert!(
                        run.failed_the_suite(),
                        "{} failed no check of the suite: it panicked at {file}:{line}",
                        stringify!($scenario)
                    ),
                }
            }
        )*
    };
}

fn s(flaw: S) -> MockHarness {
    MockHarness::with_seeder_flaw(flaw)
}

fn v(flaw: V) -> MockHarness {
    MockHarness::with_viewer_flaw(flaw)
}

/// A flawed seeder whose mint answers reads on a later poll: for defects only an engine
/// whose reads yield can have.
fn r(flaw: S) -> MockHarness {
    MockHarness::with_seeder_flaw_round_trip(flaw)
}

